    /**
     * Render an SVG icon with customized attributes.
     */
    public static function render(string $name, string $class = '', int|string $size = '1.15em'): string
    {
        $normalized = self::normalizeName($name);
        $inner = self::$icons[$normalized] ?? self::$icons['info-circle'];

        $width = is_numeric($size) ? "{$size}px" : $size;
        $height = is_numeric($size) ? "{$size}px" : $size;

        $cssClass = trim("svg-icon svg-icon-{$normalized} {$class}");

        return sprintf(
            '<svg xmlns="http://www.w3.org/2000/svg" width="%s" height="%s" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="%s" aria-hidden="true">%s</svg>',
            htmlspecialchars($width),
            htmlspecialchars($height),
            htmlspecialchars($cssClass),
            $inner
        );
    }

    /**
